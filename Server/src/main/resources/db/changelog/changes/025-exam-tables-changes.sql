DROP TABLE exams;
CREATE TABLE exams (id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, name VARCHAR(255) NOT NULL, code VARCHAR(6) NOT NULL UNIQUE, time_limit INT NOT NULL);
CREATE TABLE exam_questions (id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, text VARCHAR(255) NOT NULL, points INT NOT NULL, exam_id INT NOT NULL REFERENCES exams(id) ON DELETE CASCADE);
CREATE TABLE exam_answers (id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, text VARCHAR(255) NOT NULL, correct BOOLEAN NOT NULL, question_id INT NOT NULL REFERENCES exam_questions(id) ON DELETE CASCADE);

